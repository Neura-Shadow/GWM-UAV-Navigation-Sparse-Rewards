"""P7 M1 specifications: the frozen layout sets and the randomized flight schedule (contract §4, plan §4.1-§4.3).

Offline only: never starts a simulator or any runtime, and changes no P2-P6 file.
* **Layouts:** the bound P5 generator, unchanged (`p5_layouts.generate` and its admission filter `rejection`), over
  the fresh seed ranges of decision D8. The P5 split-match exclusion uses the 1,650 P5 layouts. They are regenerated
  here, and the run stops unless they reproduce the P5 dataset manifest and readiness report exactly.
  * Each box gets the name `p7_box_<k>`, k being its position in the generator's list.
  * Each layout's world is generated by the bound `p4_worlds.generate` from the pinned PX4 default world (the P3
    manifest's asset digest), through `scenario_mapping`, the mapping the P7 runner uses (M2). Its SHA-256 is recorded.
* **Schedule:** a deterministic function of the layout document's canonical SHA-256, so it cannot be chosen after
  seeing the layouts.
  * The random stream is a SHA-256 counter, and orders are Fisher-Yates shuffles from the end. Both are pure
    standard library.
  * Pilot: the 10 pilot layouts, 2 repeats each, as 20 pairs in random order. Each layout flies one repeat with P4
    first and one with P5 first (so 10/10 overall); repeats are numbered in flight order.
  * Confirmatory: two pre-registered schedules, for 200 and 250 pairs. Each is a random order of the first N
    layouts in seed order, in blocks of 20 pairs, with the first controller balanced inside every block. The pilot
    rule of the analysis plan picks one before the first confirmatory flight.

Hashes are canonical (sorted keys, compact JSON), so they do not depend on line endings.

Usage (WSL, from /tmp, PYTHONDONTWRITEBYTECODE=1):
  p7_specs.py generate --layouts OUT.json --schedule OUT.json   (exclusive create)
  p7_specs.py verify --layouts PATH --schedule PATH              (regenerates both; any difference fails)
"""
import argparse
import hashlib
import json
import multiprocessing
import os
from pathlib import Path
import sys

P7 = Path(__file__).resolve().parents[1]
REPO = P7.parents[1]
SIM, P4, P5 = REPO / "simulation/px4_gazebo", REPO / "simulation/px4_gazebo_p4", REPO / "simulation/px4_gazebo_p5"
for _path in (P5 / "training", P4 / "scripts", SIM / "validation"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

import numpy  # noqa: E402
import p5_layouts  # noqa: E402
from p3_provenance import atomic_json, canonical_sha256, digest, strict_json  # noqa: E402
from p4_worlds import generate as generate_world  # noqa: E402

LAYOUTS_CONTRACT, SCHEDULE_CONTRACT = "p7-layouts-v1", "p7-schedule-v1"
OUTCOME_LABEL = "p7_not_predeclared"  # decision D13: non-null, outside the accepted labels
BOX_NAME = "p7_box_%d"
NUMPY = "1.26.4"  # the version that reproduces the P5 splits (P5 training report; M0 audit §4.1)
SETS = {"pilot": {"prefix": "p7p", "seed_base": 5_000_000, "count": 10},
        "confirmatory": {"prefix": "p7c", "seed_base": 4_000_000, "count": 250, "primary_count": 200}}
CONFIRMATORY_SIZES = (200, 250)
BLOCK_PAIRS = 20
PILOT_REPEATS = 2
CONTROLLERS = ("p4", "p5")
CHUNK = 256
P3_MANIFEST = "state/p3-candidate-087722b.json"
WORLD_ASSET = "Tools/simulation/gz/worlds/default.sdf"
MODEL = P5 / "models/p5-ranker-ee006a805ba9c327a29f8f97ef6a13d0608b8459b37f0ca873a5155c59eaf73c"
GENERATOR_FILES = ("simulation/px4_gazebo_p5/training/p5_layouts.py", "simulation/px4_gazebo_p5/training/p5_oracle.py",
                   "simulation/px4_gazebo_p5/training/p5_render.py", "simulation/px4_gazebo_p5/training/p5_episode.py",
                   "simulation/px4_gazebo_p5/training/p5_paths.py", "simulation/px4_gazebo_p4/scripts/p4_worlds.py",
                   "simulation/px4_gazebo_p4/configs/p4_scenarios.json", "simulation/px4_gazebo_p4/configs/p4_avoidance.yaml",
                   "simulation/px4_gazebo/configs/p3_sensors.yaml", "simulation/px4_gazebo/configs/p2_control.yaml")


def sim_root():
    return Path(os.environ.get("GWM_SIM_ROOT", str(Path.home() / "uav_autonomy")))


# ---- the P5 split-match exclusion set ---------------------------------------------------------------------------
def p5_exclusion(pool):
    """The 1,650 P5 layouts, regenerated and checked against the P5 records; any difference stops."""
    manifest = strict_json(str(MODEL) + ".dataset_manifest.json")
    readiness = strict_json(str(MODEL) + ".readiness_report.json")
    boxes = []
    for name in ("train", "validation", "held_out"):
        got = p5_layouts.split(name, mapper=lambda fn, seeds: pool.imap(fn, seeds, chunksize=8))
        record = manifest["splits"][name]
        if any(got[k] != record[k] for k in ("seed_base", "seeds_tried", "rejected")) or len(got["layouts"]) != record["count"]:
            raise ValueError("the bound generator does not reproduce the P5 %s split here" % name)
        if name == "held_out" and got["layouts"] != readiness["layouts"]:
            raise ValueError("the regenerated held-out layouts differ from the P5 readiness report")
        boxes += [layout["boxes"] for layout in got["layouts"]]
    return boxes


# ---- screening the fresh seed ranges ----------------------------------------------------------------------------
def named(boxes):
    return [{"name": BOX_NAME % k, "center": list(b["center"]), "size": list(b["size"])} for k, b in enumerate(boxes)]


def screen(pool, spec, exclusion):
    """The first `count` admitted layouts in seed order, with every rejection counted."""
    admitted, rejected, tried = [], {}, 0
    base = spec["seed_base"]
    while len(admitted) < spec["count"]:
        if tried >= p5_layouts.SEED_RANGE:
            raise RuntimeError("seed range exhausted")
        for layout, reason in pool.imap(p5_layouts._screen, range(base + tried, base + tried + CHUNK), chunksize=8):
            if len(admitted) == spec["count"]:
                break
            tried += 1
            if reason is None and any(p5_layouts.matches(layout["boxes"], other) for other in exclusion):
                reason = "p5_split_match"
            if reason is None:
                admitted.append({"id": "%s-%07d" % (spec["prefix"], layout["seed"]), "index": len(admitted),
                                 "seed": layout["seed"], "family": layout["family"], "boxes": named(layout["boxes"])})
            else:
                rejected[reason] = rejected.get(reason, 0) + 1
    return {"seed_base": base, "seeds_tried": tried, "rejected": dict(sorted(rejected.items())), "layouts": admitted}


# ---- worlds -----------------------------------------------------------------------------------------------------
def scenario_mapping(layouts):
    """The `p4_scenarios.json`-shaped mapping the P7 runner gives the accepted P4 runner (contract §5, D13)."""
    accepted = strict_json(P4 / "configs/p4_scenarios.json")
    return {"schema_version": 1, "contract": "p7-scenarios-v1", "frame": accepted["frame"],
            "scenarios": {layout["id"]: {"boxes": layout["boxes"], "outcome": OUTCOME_LABEL, "fault": None}
                          for layout in layouts},
            "ground_fixtures": {}, "box_height_m": accepted["box_height_m"],
            "box_center_height_m": accepted["box_center_height_m"]}


def base_world():
    """The pinned PX4 default world, located as the accepted P4 runner does and checked against the P3 manifest."""
    root = sim_root()
    pinned = strict_json(root / P3_MANIFEST)["runtime"]["assets"][WORLD_ASSET]
    receipt = strict_json(root / "state/px4-mc-trace-built.json")
    env = (Path(receipt["build"]) / "rootfs/gz_env.sh").read_text()
    worlds = next(line.split("=", 1)[1] for line in env.splitlines() if line.startswith("export PX4_GZ_WORLDS="))
    path = Path(worlds) / "default.sdf"
    if digest(path) != pinned:
        raise ValueError("the PX4 default world differs from the pinned P3 asset")
    return path.read_text(), pinned


def world_sha256(base_text, layouts):
    mapping = scenario_mapping(layouts)
    return {layout["id"]: hashlib.sha256(generate_world(base_text, layout["id"], mapping)[0].encode()).hexdigest()
            for layout in layouts}


# ---- the layout document ----------------------------------------------------------------------------------------
def layouts_document(processes=16):
    if numpy.__version__ != NUMPY:
        raise SystemExit("NumPy %s required (found %s)" % (NUMPY, numpy.__version__))
    with multiprocessing.Pool(processes) as pool:
        exclusion = p5_exclusion(pool)
        sets = {name: screen(pool, spec, exclusion) for name, spec in SETS.items()}
    base_text, base_sha = base_world()
    for name, result in sets.items():
        worlds = world_sha256(base_text, result["layouts"])
        for layout in result["layouts"]:
            layout["world_sha256"] = worlds[layout["id"]]
        result.update({k: v for k, v in SETS[name].items() if k != "prefix"}, id_prefix=SETS[name]["prefix"])
        result["family_counts"] = {}
        for layout in result["layouts"]:
            result["family_counts"][layout["family"]] = result["family_counts"].get(layout["family"], 0) + 1
    return {"contract": LAYOUTS_CONTRACT, "schema_version": 1,
            "decisions": "D8 (layout source, seed bases, P5 split-match exclusion), D13 (declaration label); contract §4.1",
            "outcome_label": OUTCOME_LABEL, "box_name_rule": "p7_box_<k>, k = the box's position in the generator's list",
            "runtime": {"numpy": numpy.__version__, "python": sys.version.split()[0]},
            "generator_sha256": {path: digest(REPO / path) for path in GENERATOR_FILES},
            "base_world": {"asset": WORLD_ASSET, "sha256": base_sha, "pinned_by": P3_MANIFEST},
            "exclusion": {"p5_layouts": len(exclusion), "canonical_sha256": canonical_sha256(exclusion),
                          "rule": "same box count; some pairing with every centre within 0.25 m and every size within "
                                  "0.10 m (P5 contract §4.1)",
                          "sources": {"dataset_manifest_sha256": digest(str(MODEL) + ".dataset_manifest.json"),
                                      "readiness_report_sha256": digest(str(MODEL) + ".readiness_report.json")}},
            "sets": sets}


# ---- the schedule -----------------------------------------------------------------------------------------------
def draw(seed, label, i):
    return int.from_bytes(hashlib.sha256(("%s:%s:%d" % (seed, label, i)).encode()).digest(), "big")


def shuffle(items, seed, label):
    items = list(items)
    for i in range(len(items) - 1, 0, -1):
        j = draw(seed, label, i) % (i + 1)
        items[i], items[j] = items[j], items[i]
    return items


def balanced_firsts(n, seed, label):
    if n % 2:
        raise ValueError("a balanced first-controller split needs an even number of pairs")
    return shuffle([CONTROLLERS[0]] * (n // 2) + [CONTROLLERS[1]] * (n // 2), seed, label)


def pair(slot, block, index, layout, first, **extra):
    second = CONTROLLERS[1] if first == CONTROLLERS[0] else CONTROLLERS[0]
    return {"slot": slot, "block": block, "pair_in_block": index, "layout": layout, "first": first,
            "order": [first, second], **extra}


def schedule_document(layouts):
    seed = canonical_sha256(layouts)
    pilot_ids = [layout["id"] for layout in layouts["sets"]["pilot"]["layouts"]]
    order = shuffle([i for i in pilot_ids for _ in range(PILOT_REPEATS)], seed, "pilot-order")
    # Each layout flies one repeat with P4 first and one with P5 first; repeats are numbered in flight order.
    opening = {i: CONTROLLERS[draw(seed, "pilot-first-" + i, 0) % 2] for i in pilot_ids}
    pilot, seen = [], {}
    for k, i in enumerate(order):
        seen[i] = seen.get(i, 0) + 1
        first = opening[i] if seen[i] == 1 else (CONTROLLERS[1] if opening[i] == CONTROLLERS[0] else CONTROLLERS[0])
        pilot.append(pair(k + 1, 1, k + 1, i, first, repeat=seen[i]))
    confirmatory = {}
    ordered = sorted(layouts["sets"]["confirmatory"]["layouts"], key=lambda layout: layout["index"])
    for n in CONFIRMATORY_SIZES:
        order = shuffle([layout["id"] for layout in ordered[:n]], seed, "confirmatory-%d-order" % n)
        rows = []
        for b, start in enumerate(range(0, n, BLOCK_PAIRS), 1):
            block = order[start:start + BLOCK_PAIRS]
            for j, (layout, first) in enumerate(zip(block, balanced_firsts(len(block), seed, "confirmatory-%d-block-%d-first" % (n, b))), 1):
                rows.append(pair(start + j, b, j, layout, first))
        confirmatory[str(n)] = {"pairs": n, "blocks": -(-n // BLOCK_PAIRS), "flights": 2 * n, "slots": rows}
    return {"contract": SCHEDULE_CONTRACT, "schema_version": 1, "layouts_canonical_sha256": seed,
            "rng": "draw(label, i) = int(SHA-256('<layouts_canonical_sha256>:<label>:<i>')), big-endian; "
                   "Fisher-Yates from the end, j = draw(label, i) mod (i + 1)",
            "controllers": {"p4": "accepted P4 stack, manifest c110bd30", "p5": "accepted P5 stack, manifest 2becfbbb"},
            "pair_rule": "the two flights of a pair run back to back in the listed order",
            "block_pairs": BLOCK_PAIRS,
            "pilot": {"layouts": len(pilot_ids), "repeats": PILOT_REPEATS, "pairs": len(pilot), "flights": 2 * len(pilot),
                      "slots": pilot},
            "confirmatory": confirmatory,
            "selection": "the analysis plan's pilot rule selects the 200- or 250-pair schedule before the first "
                         "confirmatory flight; nothing is added, removed or reordered afterwards"}


# ---- entry ------------------------------------------------------------------------------------------------------
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("generate", "verify"):
        p = sub.add_parser(name)
        p.add_argument("--layouts", type=Path, required=True)
        p.add_argument("--schedule", type=Path, required=True)
    args = parser.parse_args(argv)
    layouts = layouts_document()
    schedule = schedule_document(layouts)
    if args.command == "generate":
        atomic_json(args.layouts, layouts, exclusive=True)
        atomic_json(args.schedule, schedule, exclusive=True)
    else:
        for path, value in ((args.layouts, layouts), (args.schedule, schedule)):
            if strict_json(path) != value:
                raise SystemExit("differs from its regeneration: %s" % path)
    print(json.dumps({"layouts_canonical_sha256": canonical_sha256(layouts),
                      "schedule_canonical_sha256": canonical_sha256(schedule)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
