def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def generate(name):
    source, expected = SOURCES[name]
    path = REPO / source
    if digest(path) != expected:
        raise SystemExit("the accepted source %s differs from its accepted hash" % source)
    text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    for old, new in EDITS[name]:
        if text.count(old) != 1:
            raise SystemExit("%s: anchor found %d times: %r" % (name, text.count(old), old[:80]))
        text = text.replace(old, new)
    return text


def main(argv):
    command = argv[0] if argv else "check"
    bad = []
    for name in SOURCES:
        text = generate(name)
        target = PACKAGE / name
        if command == "generate":
            target.write_text(text, encoding="utf-8", newline="\n")
        elif not target.exists() or target.read_text(encoding="utf-8") != text:
            bad.append(name)
    if bad:
        raise SystemExit("differs from its generation: %s" % ", ".join(bad))
    print("ok", command, sorted(SOURCES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
